#!/usr/bin/env python3
"""Generate the deterministic Luau stress fixture used by Fission.BinaryNinja.

The output is intentionally repetitive: hundreds of small functions with
different control-flow and table/closure shapes exercise the bytecode lifter at
a realistic scale while keeping the program's printed digest stable.
"""

from pathlib import Path

FUNCTIONS = 240
TEMPLATES = 6


def template(index: int, kind: int) -> str:
    name = f"stress_{index}"
    seed = index * 37 + 11
    if kind == 0:
        return f"""
local function {name}(seed)
    local total = seed + {seed % 19}
    for i = 1, (seed % 13) + 20 do
        if i % 3 == 0 then
            total += i * 2
        elseif i % 5 == 0 then
            total -= i
        else
            total += i % 7
        end
    end
    local n = 0
    while n < (seed % 7) do
        n += 1
        total += n
    end
    repeat
        total -= 1
    until total % 5 == 0
    return total
end
"""
    if kind == 1:
        return f"""
local function {name}(seed)
    local t = {{ alpha = seed, beta = seed + {seed % 23} }}
    for i = 1, 12 do
        t[i] = (t[i] or 0) + i * (seed % 4 + 1)
    end
    local sum = 0
    for key, value in pairs(t) do
        if type(value) == "number" then
            sum += value
        elseif type(key) == "string" then
            sum += #key
        end
    end
    table.sort(t)
    return sum + #t + (t[1] or 0)
end
"""
    if kind == 2:
        return f"""
local function {name}(seed, ...)
    local captured = seed
    local function step(n)
        captured += n
        return captured
    end
    for i = 1, select("#", ...) do
        step(select(i, ...))
    end
    local function finish()
        captured = captured % 100003
        return captured
    end
    return finish()
end
"""
    if kind == 3:
        return f"""
local function {name}(seed)
    local parts = {{}}
    for i = 1, (seed % 5) + 3 do
        parts[#parts + 1] = string.format("%d:%s", i, string.rep("x", i % 3 + 1))
    end
    local joined = table.concat(parts, "|")
    local found = string.find(joined, "x", 1, true) or 0
    return #joined + string.byte(joined, 1) + found
end
"""
    if kind == 4:
        return f"""
local Class{index} = {{}}
Class{index}.__index = Class{index}
function Class{index}.new(value)
    return setmetatable({{ value = value }}, Class{index})
end
function Class{index}:add(amount)
    self.value += amount
    return self
end
function Class{index}.__add(lhs, rhs)
    return Class{index}.new(lhs.value + rhs.value)
end
local function {name}(seed)
    local acc = Class{index}.new(seed + {seed % 17})
    for i = 1, 9 do
        acc:add(i * (seed % 3 + 1))
    end
    local other = Class{index}.new(seed)
    return (acc + other).value
end
"""
    return f"""
local function {name}(seed)
    local ok, err = pcall(function()
        if seed % 2 == 0 then
            error("even seed")
        end
        return seed
    end)
    local co = coroutine.create(function(value)
        local yielded = coroutine.yield(value + 1)
        return yielded + 2
    end)
    local started, a = coroutine.resume(co, seed)
    local resumed, b = coroutine.resume(co, seed)
    local bits = bit32.bxor(seed, 0xA5A5)
    bits = bit32.lshift(bits, seed % 5)
    bits = bit32.band(bits, 0xFFFF)
    return (ok and 1 or 0) + (started and a or 0) + (resumed and b or 0) + bits + math.floor(math.sqrt(seed * seed + 1))
end
"""


def main() -> None:
    root = Path(__file__).resolve().parent
    pieces = [
        "-- Generated by generate_stress.py. Do not edit by hand.\n",
        "local results = {}\n",
        "local functions = {}\n",
    ]
    names = []
    for index in range(1, FUNCTIONS + 1):
        name = f"stress_{index}"
        names.append(name)
        pieces.append("do\n")
        pieces.append(template(index, (index - 1) % TEMPLATES))
        pieces.append(f"    functions[{index}] = {name}\n")
        pieces.append("end\n")

    pieces.append("\nlocal total = 0\n")
    pieces.append("for index, fn in ipairs(functions) do\n")
    pieces.append("    local ok, value = pcall(fn, index * 37 + 5, index, index + 1, index + 2)\n")
    pieces.append("    if ok then\n")
    pieces.append("        total = (total + value) % 1000003\n")
    pieces.append("        results[#results + 1] = value\n")
    pieces.append("    else\n")
    pieces.append("        results[#results + 1] = -1\n")
    pieces.append("    end\n")
    pieces.append("end\n")
    pieces.append('print("stress", #results, total, results[1], results[#results])\n')
    pieces.append('print("digest", #results, #table.concat(results, ","))\n')

    (root / "stress.luau").write_text("".join(pieces), encoding="utf-8")
    print(f"wrote {root / 'stress.luau'} ({FUNCTIONS} functions)")


if __name__ == "__main__":
    main()
